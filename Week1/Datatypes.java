package Week1;

public class Datatypes {
    public static void main(String[] args) {
//        Integer data type
        int a = 10;
//        String data type
        String s = "vivek";
//        Character Datatype
        char c = 'v';
//        boolean datatype
        boolean ans = true;
//        float datatype
        float num = 4.2345678F;
//        double datatype
        double d = 123.345556;
        System.out.println(a);
        System.out.println(c);
        System.out.println(ans);
        System.out.println(num);
        System.out.println(d);
    }
}
